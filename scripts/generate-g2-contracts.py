#!/usr/bin/env python3
"""Generate canonical dependency-free C# DTOs from the Master-owned G2 model schema."""
from pathlib import Path
import json
import re
from xml.sax.saxutils import escape

ROOT = Path(__file__).resolve().parents[1]
SCHEMA = json.loads((ROOT / 'docs/contracts/g2-models.json').read_text())
TARGET = ROOT / 'backend/src/Contracts/OntologyPlatform.Contracts'
TARGET.mkdir(parents=True, exist_ok=True)
lines = ['// <auto-generated />', '// 唯一来源：docs/contracts/g2-models.json；运行scripts/generate-g2-contracts.py生成。', '#nullable enable', 'using System.Text.Json.Serialization;', '', 'namespace OntologyPlatform.Contracts;', '']
for name, values in SCHEMA['enums'].items():
    lines += ['/// <summary>明确冻结的'+name+'协议枚举，未知值不得静默接受。</summary>', '[JsonConverter(typeof(StrictStringEnumConverter<'+name+'>))]', 'public enum '+name, '{']
    for value in values:
        member = ''.join(word[:1].upper()+word[1:].lower() if word.isupper() else word[:1].upper()+word[1:] for word in re.split('[_.]',value))
        lines += ['    /// <summary>协议值'+escape(value)+'。</summary>', '    [JsonStringEnumMemberName("'+value+'")]', '    '+member+',', '']
    lines += ['}', '']
lines += ['/// <summary>事件载荷唯一判别基类，kind与事件类型一致。</summary>', '[JsonPolymorphic(TypeDiscriminatorPropertyName = "kind")]']
for name, kind in SCHEMA['payloadDiscriminators'].items():
    lines += ['[JsonDerivedType(typeof('+name+'), "'+kind+'")]']
lines += ['public abstract record ExecutionPayload;', '']
for name, definition in SCHEMA['models'].items():
    lines += ['/// <summary>'+escape(definition['description'])+'</summary>', '[JsonUnmappedMemberHandling(JsonUnmappedMemberHandling.Disallow)]', 'public sealed record '+name+(' : '+definition['base']+', IJsonOnDeserialized, IJsonOnSerializing' if definition['base'] else ' : IJsonOnDeserialized, IJsonOnSerializing'), '{']
    for field in definition['fields']:
        t = field['type']
        default = '[]' if t.endswith('[]') else 'null' if t.endswith('?') else 'string.Empty' if t == 'string' else 'default' if t in ['int','long','bool','double','DateTimeOffset','System.Text.Json.JsonElement'] or t in SCHEMA['enums'] else 'default!'
        lines += ['    /// <summary>'+escape(field['description'])+'</summary>']
        if field.get('required', True):
            lines += ['    [JsonRequired]']
        if field.get('omitNull', False):
            lines += ['    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]']
        lines += ['    public '+t+' '+field['name']+' { get; init; } = '+default+';', '']
    lines += ['    /// <summary>反序列化后检查本合同的非空及判别边界。</summary>', '    void IJsonOnDeserialized.OnDeserialized() => G2WireRules.Validate(this);', '', '    /// <summary>持久化或输出前检查同一个合同边界。</summary>', '    void IJsonOnSerializing.OnSerializing() => G2WireRules.Validate(this);', '}', '']
(TARGET/'G2Models.g.cs').write_text('\n'.join(lines))
print('Generated canonical DTOs:',len(SCHEMA['models']))


def openapi_field(csharp):
    """Map only canonical explicit DTO field kinds to standard Schema, preserving nullability."""
    if csharp.endswith('?'):
        return {'anyOf': [openapi_field(csharp[:-1]), {'type': 'null'}]}
    if csharp.endswith('[]'):
        return {'type': 'array', 'items': openapi_field(csharp[:-2])}
    primitive = {'string': {'type': 'string'}, 'int': {'type': 'integer', 'format': 'int32'}, 'long': {'type': 'integer', 'format': 'int64'}, 'bool': {'type': 'boolean'}, 'double': {'type': 'number', 'format': 'double'}, 'DateTimeOffset': {'type': 'string', 'format': 'date-time'}, 'System.Text.Json.JsonElement': {}}
    return primitive.get(csharp, {'$ref': '#/components/schemas/' + csharp})


schemas = {name: {'type': 'string', 'enum': values} for name, values in SCHEMA['enums'].items()}
schemas['ExecutionPayload'] = {'oneOf': [{'$ref': '#/components/schemas/' + name} for name in SCHEMA['payloadDiscriminators']], 'discriminator': {'propertyName': 'kind', 'mapping': {kind: '#/components/schemas/' + name for name, kind in SCHEMA['payloadDiscriminators'].items()}}}
for name, definition in SCHEMA['models'].items():
    fields = {field['name'][:1].lower() + field['name'][1:]: dict(openapi_field(field['type']), description=field['description']) for field in definition['fields']}
    for field in definition['fields']:
        if 'const' in field:
            fields[field['name'][:1].lower()+field['name'][1:]] = {'type': 'string', 'const': field['const']}
    if name in SCHEMA['payloadDiscriminators']:
        fields = {'kind': {'type': 'string', 'const': SCHEMA['payloadDiscriminators'][name]}, **fields}
    required = [field['name'][:1].lower() + field['name'][1:] for field in definition['fields'] if field.get('required', True)]
    if name in SCHEMA['payloadDiscriminators']:
        required = ['kind', *required]
    schemas[name] = {'type': 'object', 'description': definition['description'], 'required': required, 'properties': fields, 'additionalProperties': False}

# 标准Schema必须表达与C#运行时同样的精确分支约束。
fields = schemas['SemanticDatum']['properties']
schemas['SemanticDatum'] = {'oneOf': [dict(type='object', required=list(fields), additionalProperties=False, properties={key: ({'type': 'string', 'const': branch} if key == 'kind' else {'$ref': '#/components/schemas/' + {'ontology': 'OntologyDescription', 'entity': 'SemanticEntity', 'relationship': 'SemanticRelationship'}[key]} if key == branch else {'type': 'null'}) for key in fields}) for branch in ['ontology', 'entity', 'relationship']], 'discriminator': {'propertyName': 'kind'}}
fields = schemas['ExecutionEvent']['properties']
schemas['ExecutionEvent'] = {'oneOf': [dict(type='object', required=list(fields), additionalProperties=False, properties={key: ({'type': 'string', 'const': kind} if key == 'eventType' else {'type': 'integer', 'enum': [1]} if key == 'schemaVersion' else {'$ref': '#/components/schemas/' + payload} if key == 'payload' else value) for key, value in fields.items()}) for payload, kind in SCHEMA['payloadDiscriminators'].items()], 'discriminator': {'propertyName': 'eventType'}}

# 始终生成独立Schema来源，运行端点快照导出不反向覆盖唯一模型合同。
(ROOT / 'docs/contracts/g2-schemas.openapi.json').write_text(json.dumps({'openapi': '3.1.0', 'info': {'title': 'Generated G2 DTO schemas; not runtime route evidence', 'version': '1.0.0'}, 'paths': {}, 'components': {'schemas': schemas}}, ensure_ascii=False, indent=2) + '\n')

# 只在产品端点首次导出前提供标明来源的合同schema；不得用此空paths证明实际OpenAPI已验收。
openapi_path = ROOT / 'docs/contracts/g2-platform.openapi.json'
if not openapi_path.exists() or 'x-contract-source' in json.loads(openapi_path.read_text()):
    openapi_path.write_text(json.dumps({'openapi': '3.1.0', 'info': {'title': 'G2 frozen contract schemas; runtime endpoint verification NOT_RUN', 'version': '1.0.0'}, 'x-contract-source': 'g2-models.json; schema-only bootstrap, replace with real runtime export before acceptance', 'paths': {}, 'components': {'schemas': schemas}}, ensure_ascii=False, indent=2) + '\n')
